/**
 * Which permission every write needs (frontend SPEC-358, root ABSOLUTE RULE 13) — the same
 * permission the backend's route policy enforces (backend SPEC-317, `services/access/policy.py`).
 * `member`: anyone signed in may (their own account, chat-free reads, sign-in and onboarding, where
 * the organization's creator is its owner). `owner`: only the owner (the service checks it).
 *
 * `tests/role-gate-coverage.test.ts` fails the build when a write function in `services/*.ts`
 * or a screen that writes directly is missing here, when an entry is stale, and when a screen
 * that calls a non-member write does not gate it by these permissions. A new write = one row.
 */
