/**
 * SPEC-337 — the old platform name never creeps back. The product is named once, in
 * `lib/product.ts`; every other file reads it from there. A match outside the allowlist
 * below fails the build.
 */
import { readFileSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SCANNED = ["app", "features", "components", "lib", "hooks"];
const OLD_NAME = /ecommerce[ -]?fte/i;

/** File → why the old name may stay there. */
const ALLOWED: Record<string, string> = {
  "lib/ci/content.ts": "generated by tools/build_ci_content.py from historical client reports",
  "lib/ci/content-recent.ts":
    "SPEC-369: the build reports since Sep 26, a historical record of days before the rename",
  "lib/nudge.ts": "localStorage key prefix — renaming it resets every user's dismissals",
  "lib/voice.ts": "localStorage key prefix — renaming it resets every user's voice-reply choice",
  "lib/answer-visual.ts": "localStorage key prefix — renaming it resets every user's text/chart choice",
  "components/shared/brand-logo.tsx": "cites the marketing site's repo path, ecommerce-fte/components/ui.tsx",
};

function* files(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else if (/\.(tsx?|css|mjs|js)$/.test(entry.name)) yield path;
  }
}

describe("the old platform name", () => {
  it("appears only in allowlisted files", () => {
    const offenders: string[] = [];
    for (const top of SCANNED) {
      for (const path of files(join(ROOT, top))) {
        const rel = relative(ROOT, path).split("\\").join("/");
        if (rel in ALLOWED) continue;
        readFileSync(path, "utf8")
          .split("\n")
          .forEach((line, i) => {
            if (OLD_NAME.test(line)) offenders.push(`${rel}:${i + 1}: ${line.trim()}`);
          });
      }
    }
    expect(offenders).toEqual([]);
  });

  it("allowlists only files that still need it", () => {
    const stale = Object.keys(ALLOWED).filter((rel) => !OLD_NAME.test(readFileSync(join(ROOT, rel), "utf8")));
    expect(stale).toEqual([]);
  });
});
